export type Translations = (typeof translations)[keyof typeof translations];

export function getTranslations(locale: string, fallbackLocale: string = 'es'): Translations {
  const normalized = normalizeLocale(locale || fallbackLocale);
  const fallback = normalizeLocale(fallbackLocale);
  return (
    translations[normalized as keyof typeof translations] ||
    translations[fallback as keyof typeof translations] ||
    translations.es
  );
}

export function getLocaleKey(locale: string, fallbackLocale: string = 'es'): string {
  const normalized = normalizeLocale(locale || fallbackLocale);
  if (translations[normalized as keyof typeof translations]) {
    return normalized;
  }
  return normalizeLocale(fallbackLocale);
}
